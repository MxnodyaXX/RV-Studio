// PDF and Excel export. Both libraries are loaded on demand so they never
// weigh down the main bundle.
import { formatLKR } from './money'

export type ExportTable = {
  title: string
  columns: { header: string; align?: 'left' | 'right'; money?: boolean }[]
  /** Money columns are given in cents; other cells as text. */
  rows: (string | number | null)[][]
  /** Optional bold total row (same shape as rows). */
  total?: (string | number | null)[]
}

export type ExportDocument = {
  fileName: string
  title: string
  subtitle: string
  summary?: { label: string; value: string }[]
  tables: ExportTable[]
  footer?: string
}

function cellText(v: string | number | null, money?: boolean): string {
  if (v === null || v === undefined) return ''
  if (money && typeof v === 'number') return formatLKR(v)
  return String(v)
}

export async function exportPdf(doc: ExportDocument) {
  const [{ jsPDF }, { default: autoTable }] = await Promise.all([import('jspdf'), import('jspdf-autotable')])
  const pdf = new jsPDF({ unit: 'pt', format: 'a4', orientation: doc.tables.some((t) => t.columns.length > 6) ? 'landscape' : 'portrait' })
  const width = pdf.internal.pageSize.getWidth()
  const navy: [number, number, number] = [20, 38, 61]

  pdf.setFillColor(...navy)
  pdf.rect(0, 0, width, 64, 'F')
  pdf.setTextColor(255, 255, 255)
  pdf.setFont('helvetica', 'bold')
  pdf.setFontSize(15)
  pdf.text('RV BUSINESS HUB', 40, 30)
  pdf.setFont('helvetica', 'normal')
  pdf.setFontSize(10)
  pdf.text(doc.title, 40, 48)
  pdf.text(doc.subtitle, width - 40, 48, { align: 'right' })

  let y = 88
  pdf.setTextColor(30, 41, 59)
  if (doc.summary?.length) {
    const colW = (width - 80) / Math.min(doc.summary.length, 4)
    doc.summary.forEach((s, i) => {
      const x = 40 + (i % 4) * colW
      const row = Math.floor(i / 4)
      pdf.setFontSize(8)
      pdf.setTextColor(100, 116, 139)
      pdf.text(s.label.toUpperCase(), x, y + row * 38)
      pdf.setFontSize(12)
      pdf.setTextColor(15, 23, 42)
      pdf.setFont('helvetica', 'bold')
      pdf.text(s.value, x, y + row * 38 + 16)
      pdf.setFont('helvetica', 'normal')
    })
    y += Math.ceil(doc.summary.length / 4) * 38 + 12
  }

  for (const t of doc.tables) {
    pdf.setFontSize(11)
    pdf.setFont('helvetica', 'bold')
    pdf.setTextColor(15, 23, 42)
    pdf.text(t.title, 40, y)
    pdf.setFont('helvetica', 'normal')
    autoTable(pdf, {
      startY: y + 8,
      margin: { left: 40, right: 40 },
      head: [t.columns.map((c) => c.header)],
      body: t.rows.map((r) => r.map((v, i) => cellText(v, t.columns[i]?.money))),
      foot: t.total ? [t.total.map((v, i) => cellText(v, t.columns[i]?.money))] : undefined,
      styles: { fontSize: 8.5, cellPadding: 5, textColor: [30, 41, 59] },
      headStyles: { fillColor: navy, textColor: 255, fontStyle: 'bold' },
      footStyles: { fillColor: [241, 245, 249], textColor: [15, 23, 42], fontStyle: 'bold' },
      alternateRowStyles: { fillColor: [248, 250, 252] },
      columnStyles: Object.fromEntries(t.columns.map((c, i) => [i, { halign: c.align ?? (c.money ? 'right' : 'left') }])),
    })
    y = ((pdf as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY ?? y) + 28
  }

  const pages = pdf.getNumberOfPages()
  for (let i = 1; i <= pages; i++) {
    pdf.setPage(i)
    pdf.setFontSize(8)
    pdf.setTextColor(100, 116, 139)
    const h = pdf.internal.pageSize.getHeight()
    pdf.text(doc.footer ?? 'Generated by RV BUSINESS HUB · Amounts in LKR · Asia/Colombo', 40, h - 20)
    pdf.text(`Page ${i} of ${pages}`, width - 40, h - 20, { align: 'right' })
  }
  pdf.save(`${doc.fileName}.pdf`)
}

export async function exportExcel(doc: ExportDocument) {
  const { default: writeXlsxFile } = await import('write-excel-file/browser')
  const sheets = doc.tables.map((t) => {
    const header = t.columns.map((c) => ({ value: c.header, fontWeight: 'bold' as const }))
    const toCell = (v: string | number | null, i: number, bold = false) => {
      const col = t.columns[i]
      if (col?.money && typeof v === 'number') return { value: v / 100, type: Number, format: '#,##0.00', ...(bold ? { fontWeight: 'bold' as const } : {}) }
      if (typeof v === 'number') return { value: v, type: Number, ...(bold ? { fontWeight: 'bold' as const } : {}) }
      return { value: v ?? '', type: String, ...(bold ? { fontWeight: 'bold' as const } : {}) }
    }
    const data = [
      [{ value: `${doc.title} — ${t.title}`, fontWeight: 'bold' as const }],
      [{ value: doc.subtitle }],
      [],
      header,
      ...t.rows.map((r) => r.map((v, i) => toCell(v, i))),
      ...(t.total ? [t.total.map((v, i) => toCell(v, i, true))] : []),
    ]
    return {
      sheet: t.title.replace(/[\\/?*[\]:]/g, ' ').slice(0, 31),
      data,
      columns: t.columns.map((c) => ({ width: c.money ? 18 : Math.max(14, c.header.length + 4) })),
    }
  })
  await writeXlsxFile(sheets as never).toFile(`${doc.fileName}.xlsx`)
}
